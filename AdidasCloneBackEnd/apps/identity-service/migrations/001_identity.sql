BEGIN;

CREATE TABLE IF NOT EXISTS identity_accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash TEXT,
  roles TEXT[] NOT NULL DEFAULT ARRAY['CUSTOMER']::TEXT[]
    CHECK (cardinality(roles) > 0 AND roles <@ ARRAY['CUSTOMER','ADMIN']::TEXT[]),
  status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SUSPENDED','DELETED')),
  email_verified_at TIMESTAMPTZ,
  password_reset_required BOOLEAN NOT NULL DEFAULT false,
  token_version INTEGER NOT NULL DEFAULT 1 CHECK (token_version > 0),
  provisioning_state TEXT NOT NULL DEFAULT 'PENDING' CHECK (provisioning_state IN ('PENDING','READY')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX IF NOT EXISTS identity_accounts_email_lower ON identity_accounts (lower(email));

CREATE TABLE IF NOT EXISTS identity_refresh_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id UUID NOT NULL,
  account_id INTEGER NOT NULL REFERENCES identity_accounts(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  parent_id UUID REFERENCES identity_refresh_sessions(id),
  replaced_by UUID REFERENCES identity_refresh_sessions(id),
  revoked_at TIMESTAMPTZ,
  client_fingerprint_hash CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS identity_refresh_account_active
  ON identity_refresh_sessions(account_id, expires_at) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS identity_refresh_family ON identity_refresh_sessions(family_id);

CREATE TABLE IF NOT EXISTS identity_challenges (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id INTEGER NOT NULL REFERENCES identity_accounts(id) ON DELETE CASCADE,
  purpose TEXT NOT NULL CHECK (purpose IN ('EMAIL_VERIFY','PASSWORD_RESET')),
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  requested_ip_hash CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS identity_challenges_account_recent
  ON identity_challenges(account_id, purpose, created_at DESC);
CREATE INDEX IF NOT EXISTS identity_challenges_active_expiry
  ON identity_challenges(expires_at) WHERE consumed_at IS NULL;

CREATE TABLE IF NOT EXISTS identity_login_throttles (
  throttle_key CHAR(64) PRIMARY KEY,
  window_started_at TIMESTAMPTZ NOT NULL,
  failure_count INTEGER NOT NULL DEFAULT 0 CHECK (failure_count >= 0),
  blocked_until TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS identity_outbox (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  topic VARCHAR(180) NOT NULL,
  envelope JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  published_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS identity_outbox_pending
  ON identity_outbox(created_at, id) WHERE published_at IS NULL;

CREATE TABLE IF NOT EXISTS identity_audit (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  event_type VARCHAR(80) NOT NULL,
  account_id INTEGER REFERENCES identity_accounts(id) ON DELETE SET NULL,
  actor_ip_hash CHAR(64),
  metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS identity_audit_account_history
  ON identity_audit(account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS identity_audit_event_history
  ON identity_audit(event_type, created_at DESC);

COMMIT;
